async def seed_routes():
    async with async_session() as db:
        created = 0
        for route_data in DEFAULT_ROUTES:
            existing = (await db.execute(
                select(Route).where(Route.control_id == route_data["control_id"])
            )).scalar_one_or_none()
            if existing:
                continue

            db.add(Route(**route_data))
            created += 1

        await db.commit()
        print(f"Routes seeded: {created} new, {len(DEFAULT_ROUTES) - created} already existed.")
