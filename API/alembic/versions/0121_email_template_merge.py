"""Merge ``tbl_email_templates`` into the central library
(``tasks/template-library`` Step 10).

What this migration does, in one transaction:

1. Backfills every ``tbl_email_templates`` row into
   ``tbl_message_templates`` (channel=email, name copied, body_text =
   the email's body_text, subject + preview_text mapped from the
   email row, variables JSONB from ``variables_used``,
   ``internal_status`` mapped — soft-deleted → archived; active →
   published; inactive → draft).
2. Inserts one ``tbl_message_template_versions`` v=1 row per central
   row, marked "Backfilled from email template".
3. Builds the bridge mapping ``old_id → new_id`` and UPDATEs every
   ``tbl_email_sequence_steps.template_id`` value.
4. Drops the old FK constraint on ``tbl_email_sequence_steps.template_id``
   (constraint name found dynamically via ``information_schema`` — the
   rename to ``tbl_`` prefix in migration 0087 might have rewritten it).
5. Adds the new FK to ``tbl_message_templates(id)``.
6. RENAMES ``tbl_email_templates`` → ``_legacy_tbl_email_templates``
   so the data survives as a manual safety-net for one release. A
   follow-up cleanup PR drops the renamed table once operators sign
   off.

Reversibility: downgrade renames the legacy table back, drops the
new FK + restores the old FK, deletes the central rows that were
backfilled, deletes the version rows. Existing email-sequence
behaviour resumes against the original tbl_email_templates rows.

Status mapping (`tbl_email_templates.is_active` + `deleted_at` →
``tbl_message_templates.internal_status`` / ``external_status``):

    deleted_at NOT NULL   → internal archived    / external n_a
    is_active=true        → internal published   / external n_a
    is_active=false       → internal draft       / external n_a

Email has no provider review pipeline — external_status stays n_a
for every row (matches Step 1's schema default for non-WA channels).

Chains after ``0120_wa_template_backfill``.

Revision ID: 0121_email_template_merge
Revises: 0120_wa_template_backfill
Create Date: 2026-06-25 17:00:00.000000
"""
