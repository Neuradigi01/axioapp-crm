    op.rename_table("_legacy_tbl_email_templates", "tbl_email_templates")

    # Revert the FK on sequence steps to point at tbl_email_templates.
    op.drop_constraint(
        "fk_email_seq_steps_template_central",
        "tbl_email_sequence_steps",
        type_="foreignkey",
    )

    # Unmap step.template_id values: they currently point at central
    # rows; switch them back to the original email-template ids by
    # joining on the `Backfilled from email template` version note
    # (no other field uniquely maps central → original).
    conn.execute(
        sa.text(
            """
            UPDATE tbl_email_sequence_steps s
            SET template_id = src.id
            FROM tbl_email_templates src, tbl_message_templates m
            WHERE s.template_id = m.id
              AND m.channel = 'email'
              AND m.org_id = src.org_id
              AND m.name = src.name
            """
        )
    )
    op.create_foreign_key(
        None,
        "tbl_email_sequence_steps",
        "tbl_email_templates",
        ["template_id"],
        ["id"],
    )

    # Drop the backfilled central rows + their version rows.
    conn.execute(
        sa.text(
            """
            DELETE FROM tbl_message_templates
            WHERE channel = 'email'
              AND id IN (
                SELECT template_id FROM tbl_message_template_versions
                WHERE change_note = 'Backfilled from email template'
              )
            """
        )
    )
